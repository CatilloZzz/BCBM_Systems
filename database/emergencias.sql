BEGIN;

CREATE TABLE IF NOT EXISTS tipo_emergencia (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    nombre varchar(80) NOT NULL CHECK (btrim(nombre) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS tipo_emergencia_nombre_unico
    ON tipo_emergencia (lower(nombre));

CREATE TABLE IF NOT EXISTS emergencia (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    direccion varchar(250) NOT NULL CHECK (btrim(direccion) <> ''),
    descripcion varchar(1000),
    tipo_emergencia_id integer NOT NULL REFERENCES tipo_emergencia(id),
    usuario_id integer NOT NULL REFERENCES usuario(id),
    prioridad varchar(20) NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    estado varchar(20) NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'CERRADA')),
    fecha_registro timestamp(6) without time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS emergencia_estado_fecha_idx ON emergencia (estado, fecha_registro);
CREATE INDEX IF NOT EXISTS emergencia_tipo_idx ON emergencia (tipo_emergencia_id);
CREATE INDEX IF NOT EXISTS emergencia_usuario_idx ON emergencia (usuario_id);

COMMIT;
